import assert from 'node:assert/strict';

export async function runPublicationChecks(browser, base) {
  const results = [];
  const check = async (name, test) => {
    const page = await browser.newPage();
    page.setDefaultTimeout(2500);
    const pageErrors = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    try { await page.goto(`${base}/publications.html?lang=en`); await test(page); assert.deepEqual(pageErrors, []); results.push({ name, pass: true }); }
    catch (error) { results.push({ name, pass: false, error: error.message }); }
    finally { await page.close(); }
  };
  await check('Publication defaults to All and respects explicit type', async page => {
    const data = await page.evaluate(() => ({ journals: JOURNAL_PAPERS.length, total: JOURNAL_PAPERS.length + CONFERENCE_PAPERS.length, paper: CONFERENCE_PAPERS[0] }));
    assert.equal(await page.locator('#publist .pub').count(), data.total);
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubfilters [aria-pressed="true"]').count(), 1);
    await page.reload();
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    await search.fill(data.paper.title);
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.ok(await page.locator('#publist').innerText().then(s => s.includes(data.paper.title)));
    assert.equal(await search.evaluate(el => el === document.activeElement), true);
    await page.getByRole('button', { name: 'Journal', exact: true }).click();
    await search.fill('S. Y. Lee');
    assert.equal(await page.locator('[data-set="journal"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#publist .pub').count(), data.journals);
  });
  await check('Publication year intersects type and venue search; empty results and reset retain focus', async page => {
    const paper = await page.evaluate(() => [...JOURNAL_PAPERS, ...CONFERENCE_PAPERS].find(p => p.domestic));
    await page.getByRole('button', { name: 'Domestic', exact: true }).click();
    const year = page.getByLabel('Year', { exact: true });
    await year.selectOption(String(paper.year));
    await year.focus();
    await year.press('Enter');
    assert.equal(await year.evaluate(el => el === document.activeElement), true);
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    await search.fill(paper.venue.toUpperCase());
    const expected = await page.evaluate(p => [...JOURNAL_PAPERS, ...CONFERENCE_PAPERS].filter(x => x.domestic && x.year === p.year && [x.title,x.authors,x.venue].some(s => s.toLowerCase().includes(p.venue.toLowerCase()))).length, paper);
    assert.equal(await page.locator('#publist .pub').count(), expected);
    assert.equal(await page.getByRole('status').innerText(), `${expected} ${expected === 1 ? 'publication' : 'publications'}`);
    await search.fill('<img src=x onerror="window.pubInjected=1">');
    assert.equal(await page.locator('#publist .pub').count(), 0);
    assert.equal(await page.getByRole('status').innerText(), '0 publications');
    assert.equal(await page.locator('#pubempty').isVisible(), true);
    assert.equal(await page.evaluate(() => !!window.pubInjected), false);
    const reset = page.getByRole('button', { name: 'Reset filters' });
    await reset.click();
    assert.equal(await reset.evaluate(el => el === document.activeElement), true);
    assert.equal(await search.inputValue(), '');
    assert.equal(await year.inputValue(), '');
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubempty').isVisible(), false);
  });
  await check('Publication URL restores combined filters, preserves unrelated state and supports history', async page => {
    const paper = await page.evaluate(() => CONFERENCE_PAPERS[0]);
    await page.goto(`${base}/publications.html?lang=en&campaign=lab#main`);
    await page.evaluate(() => history.replaceState({ external: { kept: true } }, '', location.href));
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    await search.fill(paper.title);
    let url = new URL(page.url());
    assert.equal(url.searchParams.get('q'), paper.title);
    assert.equal(url.searchParams.get('type'), null);
    await page.getByLabel('Year', { exact: true }).selectOption(String(paper.year));
    await page.getByRole('button', { name: 'Conference', exact: true }).click();
    url = new URL(page.url());
    assert.equal(url.searchParams.get('year'), String(paper.year));
    assert.equal(url.searchParams.get('lang'), 'en');
    assert.equal(url.searchParams.get('campaign'), 'lab');
    assert.equal(url.hash, '#main');
    assert.deepEqual(await page.evaluate(() => history.state), { external: { kept: true } });
    await page.reload();
    assert.equal(await search.inputValue(), paper.title);
    assert.equal(await page.locator('[data-set="conference"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#publist .pub').count(), 1);
    await page.goBack();
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    await page.goForward();
    assert.equal(await page.locator('[data-set="conference"]').getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Reset filters' }).click();
    url = new URL(page.url());
    for (const key of ['q', 'year', 'type']) assert.equal(url.searchParams.has(key), false);
    assert.equal(url.searchParams.get('campaign'), 'lab');
    assert.equal(url.hash, '#main');
    await page.goto(`${base}/publications.html?q=${encodeURIComponent(paper.title)}&lang=en`);
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#publist .pub').count(), 1);
    await page.goto(`${base}/publications.html?type=__proto__&year=2026oops&lang=en#main`);
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByLabel('Year', { exact: true }).inputValue(), '');
    assert.ok(await page.locator('#publist .pub').count() > 0);
    await page.goto(`${base}/publications.html?type=conference&type=journal&q=${encodeURIComponent(paper.title)}&q=ignored&year=${paper.year}&year=invalid&lang=en#main`);
    assert.equal(await search.inputValue(), paper.title);
    assert.equal(await page.locator('[data-set="conference"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByLabel('Year', { exact: true }).inputValue(), String(paper.year));
    await page.locator('[data-lang="ko"]').click();
    url = new URL(page.url());
    assert.equal(url.searchParams.get('q'), paper.title);
    assert.equal(url.searchParams.get('type'), 'conference');
    assert.equal(url.searchParams.get('lang'), 'ko');
    assert.equal(url.hash, '#main');
    await page.getByRole('button', { name: 'All', exact: true }).click();
    assert.equal(new URL(page.url()).searchParams.getAll('type').length, 1);
  });
  await check('Publication helper prose follows language while accessible controls fit mobile', async page => {
    await page.setViewportSize({ width: 320, height: 800 });
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    const box = await search.boundingBox();
    assert.ok(box.height >= 44, `Search height ${box.height} is below touch size`);
    assert.ok(box.width >= 240, `Search width ${box.width} is too narrow`);
    await page.locator('[data-lang="ko"]').click();
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), 'ko');
    assert.match(await page.locator('#pubsearch-hint').innerText(), /전체/);
    assert.equal(await search.count(), 1);
    await search.fill('unmatched-publication-query');
    assert.equal(await page.locator('#pubempty').getAttribute('lang'), 'ko');
    await page.locator('[data-lang="en"]').click();
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), null);
    assert.match(await page.locator('#pubsearch-hint').innerText(), /All/);
    assert.equal(await search.inputValue(), 'unmatched-publication-query');
    const overflow = await page.locator('.publication-tools, .publication-refine, #pubfilters').evaluateAll(els => els.some(el => { const r = el.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth; }));
    assert.equal(overflow, false);
  });
  await check('Publication keyboard filters and coalesced typing history keep selection and focus', async page => {
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    const before = await page.evaluate(() => history.length);
    await search.pressSequentially('control');
    assert.equal(await page.evaluate(() => history.length), before + 1);
    await page.goBack();
    assert.equal(await search.inputValue(), '');
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    await page.goForward();
    assert.equal(await search.inputValue(), 'control');
    const conference = page.getByRole('button', { name: 'Conference', exact: true });
    await conference.focus();
    await conference.press('Space');
    assert.equal(await conference.evaluate(el => el === document.activeElement), true);
    assert.equal(await conference.getAttribute('aria-pressed'), 'true');
    await search.fill('');
    assert.equal(await page.locator('#publist .pub').count(), await page.evaluate(() => CONFERENCE_PAPERS.length));
    const journal = page.getByRole('button', { name: 'Journal', exact: true });
    await journal.click();
    await page.reload();
    await search.fill('control');
    assert.equal(await journal.getAttribute('aria-pressed'), 'true');
  });
  await check('Publication Back and Forward restore URL language together with filters', async page => {
    await page.goto(`${base}/publications.html?lang=ko`);
    await page.getByRole('searchbox', { name: 'Search publications' }).fill('robot');
    await page.locator('[data-lang="en"]').click();
    await page.goBack();
    assert.equal(new URL(page.url()).searchParams.get('lang'), 'ko');
    assert.equal(await page.locator('[data-lang="ko"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), 'ko');
    await page.goForward();
    assert.equal(await page.locator('[data-lang="en"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), null);
    assert.equal(await page.getByRole('searchbox', { name: 'Search publications' }).inputValue(), 'robot');
    await page.reload();
    assert.equal(await page.locator('[data-lang="en"]').getAttribute('aria-pressed'), 'true');
  });
  await check('Publication Back and Forward restore explicit URL language without rewriting it', async page => {
    await page.goto(`${base}/publications.html?lang=ko&keep=a&keep=b#main`);
    const original = page.url();
    await page.getByRole('searchbox', { name: 'Search publications' }).fill('robot');
    await page.locator('[data-lang="en"]').click();
    const english = page.url();
    await page.goBack();
    assert.equal(page.url(), original);
    assert.equal(await page.locator('[data-lang="ko"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), 'ko');
    await page.reload();
    assert.equal(await page.locator('[data-lang="ko"]').getAttribute('aria-pressed'), 'true');
    await page.goForward();
    assert.equal(page.url(), english);
    assert.equal(await page.locator('[data-lang="en"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#pubsearch-hint').getAttribute('lang'), null);
    assert.equal(await page.getByRole('searchbox', { name: 'Search publications' }).inputValue(), 'robot');
  });
  await check('Publication search uses case-insensitive token AND across title, authors and venue (not phrase matching)', async page => {
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    for (const query of ['  ADAPTIVE   TRACKING  ', 'CONTACTLESS   JO   ELECTRONICS', '  contactless\tjo   electronics  ']) {
      await search.fill(query);
      const expected = await page.evaluate(q => {
        const tokens = q.trim().toLowerCase().split(/\s+/);
        return [...JOURNAL_PAPERS, ...CONFERENCE_PAPERS]
          .filter(p => tokens.every(token => `${p.title} ${p.authors} ${p.venue}`.toLowerCase().includes(token)))
          .map(p => p.title).sort();
      }, query);
      assert.ok(expected.length > 0, 'Query exercises known matching real publication data');
      assert.deepEqual((await page.locator('#publist .pub__title').allTextContents()).map(s => s.trim()).sort(), expected);
      assert.equal(await search.evaluate(el => el === document.activeElement), true);
      assert.equal(new URL(page.url()).searchParams.get('q'), query, 'Whitespace normalization is search-only; preserve the entered URL query');
    }
    await search.fill('contactless jo electronics no-such-token');
    assert.equal(await page.locator('#publist .pub').count(), 0, 'Every token must match, not any token');
    await search.fill('   ');
    assert.equal(await page.locator('#publist .pub').count(), await page.evaluate(() => JOURNAL_PAPERS.length + CONFERENCE_PAPERS.length));
  });
  await check('Token AND search intersects explicit type/year and survives coalesced history, language changes and reset', async page => {
    const search = page.getByRole('searchbox', { name: 'Search publications' });
    const year = page.getByLabel('Year', { exact: true });
    await page.goto(`${base}/publications.html?lang=ko&keep=a&keep=b#main`);
    await page.evaluate(() => history.replaceState({ marker: 'tokens' }, ''));
    const initial = page.url();
    const count = await page.evaluate(() => history.length);
    await search.pressSequentially('contactless jo electronics');
    assert.equal(await page.evaluate(() => history.length), count + 1);
    assert.equal(await page.locator('#publist .pub').count(), 1);
    await year.selectOption('2026');
    await page.locator('[data-set="journal"]').click();
    await page.locator('[data-lang="en"]').click();
    assert.equal(await page.locator('#publist .pub').count(), 1);
    await page.reload();
    assert.equal(await search.inputValue(), 'contactless jo electronics');
    assert.equal(await year.inputValue(), '2026');
    assert.equal(await page.locator('[data-set="journal"]').getAttribute('aria-pressed'), 'true');
    await search.focus();
    await page.goBack();
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('[data-lang="ko"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await search.evaluate(el => el === document.activeElement), true);
    await page.goBack();
    assert.equal(await year.inputValue(), '');
    await page.goBack();
    assert.equal(page.url(), initial);
    assert.deepEqual(await page.evaluate(() => history.state), { marker: 'tokens' });
    assert.equal(await search.inputValue(), '');
    await page.goForward();
    assert.equal(await search.inputValue(), 'contactless jo electronics');
    assert.equal(await page.locator('#publist .pub').count(), 1);
    await page.locator('[data-set="conference"]').click();
    assert.equal(await page.locator('#publist .pub').count(), 0);
    await page.locator('[data-set="all"]').click();
    await year.selectOption('2025');
    assert.equal(await page.locator('#publist .pub').count(), 0);
    await page.locator('#pubreset').click();
    assert.equal(await search.inputValue(), '');
    assert.equal(await year.inputValue(), '');
    assert.equal(await page.locator('[data-set="all"]').getAttribute('aria-pressed'), 'true');
    const url = new URL(page.url());
    assert.deepEqual(url.searchParams.getAll('keep'), ['a', 'b']);
    assert.equal(url.hash, '#main');
    assert.deepEqual(await page.evaluate(() => history.state), { marker: 'tokens' });
  });
  return results;
}
